def bag_of_words(s, words):
    bag = [0] * len(words)
    # Use clean_up_sentence to process the input 's'
    processed_s_words = clean_up_sentence(s)

    for se in processed_s_words:
        for i, w in enumerate(words):
            if w == se:
                bag[i] = 1

    return np.array(bag)

def chat():
    print("Start talking with the bot (type quit to stop)")
    while True:
        inp = input("You: ")
        if inp.lower() == "quit":
            break

        results = model.predict(np.array([bag_of_words(inp, words)]))
        results_index = np.argmax(results)

        # Get the confidence score for the top predicted intent
        confidence = results[0][results_index]

        if confidence >= 0.5:  # Check if confidence is above the threshold
            tag = labels[results_index]
            responses = intents[tag]['responses']
            print("Bot:", random.choice(responses))
        else:
            print("Bot: I don't understand.") # Default response for low confidence

chat()

