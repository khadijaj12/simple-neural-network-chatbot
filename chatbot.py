words = [] # This will hold the unique stemmed words vocabulary
labels = []
docs_x = [] # This will hold lists of stemmed words for each pattern
docs_y = []

for intent_name, intent_data in intents.items(): # Use .items() for clarity
    for pattern in intent_data["patterns"]:
        # Process each pattern using clean_up_sentence
        stemmed_pattern_words = clean_up_sentence(pattern)
        docs_x.append(stemmed_pattern_words) # Add the list of stemmed words to docs_x
        docs_y.append(intent_name)

        # Collect all unique stemmed words for the global vocabulary 'words'
        for word in stemmed_pattern_words:
            # `clean_up_sentence` already handles lowercasing, punctuation removal, and stemming.
            # So, just collect unique words.
            if word not in words:
                words.append(word)

    if intent_name not in labels:
        labels.append(intent_name)

words = sorted(list(set(words))) # Ensure unique and sorted vocabulary (already stemmed)
labels = sorted(labels)

training = []
output = []

out_empty = [0] * len(labels)

for x, doc in enumerate(docs_x): # doc here is already a list of stemmed words
    bag = []

    for w in words: # Iterate through the global stemmed vocabulary
        bag.append(1 if w in doc else 0) # Check if the stemmed word from vocabulary is in the stemmed pattern

    output_row = out_empty[:]
    output_row[labels.index(docs_y[x])] = 1

    training.append(bag)
    output.append(output_row)

training = np.array(training)
